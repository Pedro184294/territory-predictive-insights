
package br.com.territory.persistencia;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

public final class BancoDados {

    private BancoDados() {
        // Impede a instanciação desta classe utilitária.
    }

    public static void inicializar() throws SQLException {

        String sqlMedicoes = """
                CREATE TABLE IF NOT EXISTS medicoes (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    regiao_id VARCHAR(100) NOT NULL,
                    temperatura DOUBLE PRECISION NOT NULL,
                    umidade DOUBLE PRECISION NOT NULL,
                    consumo_energia DOUBLE PRECISION NOT NULL,
                    data_hora TIMESTAMP NOT NULL
                )
                """;

        String sqlAlertas = """
                CREATE TABLE IF NOT EXISTS alertas (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    regiao_id VARCHAR(100) NOT NULL,
                    nivel VARCHAR(30) NOT NULL,
                    descricao VARCHAR(500) NOT NULL,
                    data_hora TIMESTAMP NOT NULL
                )
                """;

        String sqlLeiturasSensor = """
                CREATE TABLE IF NOT EXISTS leituras_sensor (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    regiao_id VARCHAR(100) NOT NULL,
                    tipo_sensor VARCHAR(50) NOT NULL,
                    valor DOUBLE PRECISION NOT NULL,
                    unidade VARCHAR(20) NOT NULL,
                    data_hora TIMESTAMP NOT NULL
                )
                """;

        try (Connection conexao = ConexaoBanco.obterConexao();
                Statement statement = conexao.createStatement()) {

            statement.execute(sqlMedicoes);
            statement.execute(sqlAlertas);
            statement.execute(sqlLeiturasSensor);
        }
    }
}
